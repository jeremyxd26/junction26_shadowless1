# ---- review of PR #376 (a): what one did is not a what-if -------------------------------------------------

@pytest.mark.parametrize("question,lang", [
    ("How much did I spend on taxis last month?", "en"),
    ("Did I spend 10% less on taxis last month than in August?", "en"),
    ("Did I take fewer taxis in August than in July?", "en"),
    ("I spent 20% less on restaurants in August, right?", "en"),
    ("Käytinkö viime kuussa 10 % vähemmän takseihin?", "fi"),
    ("Paljonko käytin takseihin viime kuussa?", "fi"),
])
def test_a_question_about_what_one_did_is_never_a_what_if(question, lang):
    found = ask(question, lang)
    assert found.rule != "what_if" and "run_what_if" not in [c.name for c in found.calls], (question, found)


def test_the_taxi_spending_of_last_month_is_the_spending_question():
    found = ask("How much did I spend on taxis last month?")
    assert found.rule == "spending" and first(found).args["filter"] == {"mcc_groups": ["taxi"]}


