"""The what-if words without the model (#346 from PR #376, its review, #370, #377, #403). No database.

- #403: every action prompt a card can produce (all metrics, English and Finnish) is claimed by the rule it
  targets; the prompts are generated by the cards' own code and sent through rules.claim.
- Review of PR #376 (a): a question about what one did is not a what-if, even with "less" or "fewer".
- #370: the Finnish weather word declines only as a whole word ("bensaa" is fuel, not the weather).
- #377: a what-if on a known MCC group is named in words ("taxis"), any other code list by its codes.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from core.agent.model import PlanInput
from core.agent.rules import WHAT_IF_MCC_WORDS, WHAT_IF_WHICH, claim
from core.agent.toolset import KNOWN_TOOLS
from core.tools import config, peer, small_purchases, what_if

TOOLS = [{"name": t.function, "description": "", "parameters_json_schema": {}} for t in KNOWN_TOOLS]
AMOUNT = ("By how much", "Kuinka paljon")


def ask(question: str, language: str = "en"):
    return claim(PlanInput(question=question, language=language, as_of="2026-09-30", tools=TOOLS))


def first(found):
    return found.calls[0] if found.calls else None


# ---- #403: every card's action prompt is claimed by the rule it targets -----------------------------------

def card_prompts():
    """(card, metric, language, prompt, target) for every ask action the cards can produce."""
    out = []
    for i, lang in enumerate(("en", "fi")):
        for metric in config.PEER_METRICS:
            if metric in config.PEER_NO_CUT_ACTION:
                continue   # no cut is offered there (#418), so the card has no button
            target = "save_more" if metric == "spend_total" else "what_if_amount"
            out.append(("peer", metric, lang, peer.cut_prompt(metric, lang), target))
        for category in config.SMALL_PURCHASE_CATEGORIES:
            out.append(("small_purchases", category, lang, small_purchases.cut_prompt(category, lang), "what_if_amount"))
        out.append(("forecast", None, lang, config.FORECAST_TEXT["whatif_prompt"][i], "what_if_which"))
        out.append(("baskets", None, lang, config.BASKET_TEXT["action_prompt"][i], "basket_contents"))
        out.append(("profile", None, lang, config.PROFILE_TEXT["action_prompt"][i], "peers"))
    return out


@pytest.mark.parametrize("card,metric,language,prompt,target", card_prompts(),
                         ids=[f"{c}:{m}:{lang}" for c, m, lang, _, _ in card_prompts()])
def test_every_card_prompt_is_claimed_by_the_rule_it_targets(card, metric, language, prompt, target):
    found = ask(prompt, language)
    call = first(found)
    if target == "what_if_amount":       # the user named the spending: the what-if rule asks by how much
        assert found.rule == "what_if" and call.name == "ask_clarifying_question", (prompt, found)
        assert call.args["question"].startswith(AMOUNT), prompt
    elif target == "what_if_which":      # all one's spending: the what-if rule asks which
        assert found.rule == "what_if" and call.args["question"] == WHAT_IF_WHICH[0 if language == "en" else 1]
    elif target == "save_more":
        assert found.rule == "save_more" and call.name == "get_savings_plan", (prompt, found)
    elif target == "basket_contents":
        assert found.rule == "basket_contents" and call.name == "get_spending", (prompt, found)
        assert call.args["filter"] == {"baskets": ["everyday_spending"]} and call.args["group_by"] == "category"
    else:
        assert found.rule == target, (prompt, found)


def test_every_card_with_an_ask_action_is_in_the_prompt_list():
    """A new card button must join card_prompts(): the modules whose cards carry an ask action."""
    tools_dir = Path(__file__).resolve().parents[2] / "tools"
    with_ask = {p.stem for p in tools_dir.glob("*.py") if re.search(r'Action\(type="ask"', p.read_text(encoding="utf-8"))}
    assert with_ask == {card for card, *_ in card_prompts()}


