# ---- #377: a known MCC group in words ----------------------------------------------------------------------

@pytest.mark.parametrize("codes,en,fi", [("4121", "taxis", "taksit"), ("5541,5542", "fuel", "polttoaine"),
                                         ("7523", "parking", "pysäköinti"), ("4111", "public transport", "joukkoliikenne"),
                                         ("5814", "takeaway and fast food", "pikaruoka ja noutoruoka"),
                                         ("5813", "bars", "baarit"), ("7832", "cinemas", "elokuvateatterit")])
def test_a_known_mcc_group_is_named_in_words(codes, en, fi):
    sel = what_if.WhatIfSelection(kind="mcc", value=codes)
    assert (what_if._what(sel, None, "en"), what_if._what(sel, None, "fi")) == (en, fi)
    assert what_if._t("scenario", "en", pct=10, what=en) == f"Spend 10% less on {en}"


def test_any_other_code_list_keeps_its_codes():
    sel = what_if.WhatIfSelection(kind="mcc", value="4121,7523")
    assert what_if._what(sel, None, "en") == "purchases with MCC 4121, 7523"
    assert what_if._what(what_if.WhatIfSelection(kind="mcc", value="5411"), None, "fi") == "ostokset, MCC 5411"


def test_every_code_set_the_rules_plan_is_named_in_words():
    assert {tuple(sorted(codes)) for _, codes in WHAT_IF_MCC_WORDS} <= set(config.WHAT_IF_MCC_NAMES)
